BEGIN;

CREATE TABLE IF NOT EXISTS tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL
        CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'in_progress', 'completed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS tasks_created_at_id_idx
    ON tasks (created_at DESC, id DESC);

INSERT INTO tasks (id, title, status, created_at, updated_at)
SELECT
    id,
    title,
    CASE WHEN completed THEN 'completed' ELSE 'pending' END,
    created_at,
    updated_at
FROM todos
ON CONFLICT (id) DO NOTHING;

SELECT setval(
    pg_get_serial_sequence('public.tasks', 'id'),
    COALESCE(MAX(id), 1),
    MAX(id) IS NOT NULL
)
FROM tasks;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE tasks TO sa;
GRANT USAGE, SELECT ON SEQUENCE tasks_id_seq TO sa;

COMMIT;
